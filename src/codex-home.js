import { chmod, copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Default directory for all supervisor state (gitignored). */
export function defaultStateDir() {
  return process.env.CODEX_SUPERVISOR_STATE_DIR || join(REPO_ROOT, ".state");
}

export async function ensureDir(dir, mode = 0o700) {
  await mkdir(dir, { recursive: true, mode });
  await chmod(dir, mode).catch(() => {});
  return dir;
}

/** Keep only safe top-level model settings; never copy plugins/hooks/mcp/projects. */
export function extractMinimalConfig(sourceConfigText) {
  const keep = /^\s*(model|model_reasoning_effort|service_tier)\s*=\s*.+$/;
  const seen = new Set();
  const lines = [];
  for (const raw of sourceConfigText.split(/\r?\n/)) {
    const line = raw.trim();
    const match = line.match(/^(model|model_reasoning_effort|service_tier)\s*=/);
    if (keep.test(line) && match && !seen.has(match[1])) {
      seen.add(match[1]);
      lines.push(line);
    }
  }
  return lines;
}

/**
 * Prepare an isolated CODEX_HOME so the supervisor never writes into the user's
 * ~/.codex. The copy contains only auth.json (600) and a minimal config.toml.
 */
export async function prepareCodexHome({
  stateDir = defaultStateDir(),
  sourceHome = process.env.CODEX_AUTH_SOURCE || join(homedir(), ".codex"),
} = {}) {
  if (process.env.CODEX_HOME) {
    return {
      codexHome: process.env.CODEX_HOME,
      stateDir: resolve(stateDir),
      isolated: false,
      notes: ["CODEX_HOME 由环境变量显式指定，未创建隔离副本"],
    };
  }

  const base = resolve(stateDir);
  await ensureDir(base);
  const codexHome = join(base, "codex-home");
  await ensureDir(codexHome);
  const notes = [];
  let copiedAuth = false;

  const srcAuth = join(sourceHome, "auth.json");
  const dstAuth = join(codexHome, "auth.json");
  try {
    const [srcStat, dstStat] = await Promise.all([stat(srcAuth), stat(dstAuth).catch(() => null)]);
    if (!dstStat || srcStat.mtimeMs > dstStat.mtimeMs) {
      await copyFile(srcAuth, dstAuth);
      copiedAuth = true;
    }
    await chmod(dstAuth, 0o600);
  } catch {
    notes.push("未找到源 auth.json：请先在主目录执行 `codex login`");
  }

  let modelConfig = [];
  try {
    modelConfig = extractMinimalConfig(await readFile(join(sourceHome, "config.toml"), "utf8"));
  } catch {
    notes.push("未找到源 config.toml，使用 codex 默认模型");
  }

  const configPath = join(codexHome, "config.toml");
  const content = [
    "# generated by codex-supervisor: isolated CODEX_HOME (no plugins/hooks/mcp)",
    ...modelConfig,
    "",
  ].join("\n");
  await writeFile(configPath, content, { mode: 0o600 });

  return { codexHome, stateDir: base, isolated: true, copiedAuth, modelConfig, notes };
}
